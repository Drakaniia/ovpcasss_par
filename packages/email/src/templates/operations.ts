import { manilaDateTime, sheetLabel } from '../format';
import type { EmailContent } from '../provider';
import { renderShell } from '../shell';

/**
 * Operational mail (email spec §11.2, §9.5): the term-end workbook hand-off and
 * the administrator's failure digest. Neither carries a tracking number, so the
 * footer names the term or the count instead.
 */
export interface WorkbookMailData {
  type: string;
  schoolYear: string;
  semester: number;
  term: string;
  reportCount: number;
  generatedAt: string;
  generatedBy: string;
  note?: string;
  origin?: string;
  hasAttachment?: boolean;
  attachmentOmitted?: boolean;
}

export function workbookTemplate(data: WorkbookMailData): EmailContent {
  const sheet = sheetLabel(data.type);

  return renderShell({
    subject: `Monitoring workbook, ${sheet}, SY ${data.schoolYear}, ${data.term}`,
    heading: 'The monitoring workbook is attached',
    intro: [
      `The monitoring workbook for ${sheet}, ${data.term}, SY ${data.schoolYear} is attached.`,
      data.note ? data.note : '',
      data.hasAttachment
        ? ''
        : data.attachmentOmitted
          ? 'The file is large, so it is not attached. Download it from the Exports screen in the app.'
          : '',
    ].filter(Boolean),
    facts: [
      { label: 'Sheet', value: sheet },
      { label: 'Term', value: `${data.term}, SY ${data.schoolYear}` },
      { label: 'Reports included', value: String(data.reportCount) },
      { label: 'Generated at', value: manilaDateTime(data.generatedAt) },
      { label: 'Generated by', value: data.generatedBy },
    ],
    reference: `Monitoring workbook, SY ${data.schoolYear}`,
  });
}

export interface FailureDigestFailure {
  kind: string;
  to: string;
  error: string;
}

export interface FailureDigestData {
  count: number;
  failures: readonly FailureDigestFailure[];
  origin?: string;
}

export function failureDigestTemplate(data: FailureDigestData): EmailContent {
  const noun = data.count === 1 ? 'message' : 'messages';

  return renderShell({
    subject: `${data.count} ${noun} could not be delivered`,
    heading: 'Some mail could not be delivered',
    intro: [
      `The Paperless PAR system could not deliver ${data.count} ${noun}. The newest failures are listed below with the reason the provider gave.`,
      'Open the email log to inspect a message and re-send it.',
    ],
    facts: data.failures.map((failure) => ({
      label: failure.kind,
      value: `${failure.to} — ${failure.error}`,
    })),
    ...(data.origin
      ? { action: { label: 'Open the email log', url: `${data.origin}/admin/emails` } }
      : {}),
    reference: 'Daily delivery report',
  });
}
