/** The subject tag is added by the shell, so this is the editable part's ceiling. */
export const EMAIL_TEMPLATE_SUBJECT_MAX = 63;

export interface EmailTemplateBranch {
  key: string;
  label: string;
}

export interface EmailTemplateSlots {
  audience: string;
  /** Paragraph variants the kind can show; every one needs copy. */
  branches: readonly EmailTemplateBranch[];
  hasFacts: boolean;
  /** `failures` draws one row per failed message instead of editable rows. */
  factsSource: 'fixed' | 'failures';
  hasQuote: boolean;
  hasAction: boolean;
  actionTokens: readonly EmailToken[];
  /** Tokens the message cannot do its job without (spec §6.1). */
  required: readonly { path: string; token: EmailToken }[];
}

